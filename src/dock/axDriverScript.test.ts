import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

describe('WeChat session reader when CoreGraphics is empty', () => {
  const source = readFileSync('electron/wechat/axDriver.ts', 'utf8')

  it('imports CoreGraphics and falls back to the largest Accessibility window', () => {
    expect(source).toContain("ObjC.import('CoreGraphics')")
    const main = source.slice(source.indexOf('function mainWindow'), source.indexOf('function cgOwnedWindow'))
    expect(main).toContain('largestAxWindow')
    expect(main).toContain('AXWindows')
    expect(main.indexOf('cgOwnedWindow')).toBeLessThan(main.indexOf('largestAxWindow(windows)'))
    const pick = source.slice(source.indexOf('function largestAxWindow'), source.indexOf('function asWindows'))
    expect(pick).toContain('size.w < 240')
    expect(pick).toContain('size.h < 240')
    expect(pick).toContain('axSize')
  })

  it('enables manual accessibility and uses the focused window when the window list is empty', () => {
    expect(source).toContain('ObjC.unwrap(value)')
    expect(source).toContain("bid === 'com.tencent.xinWeChat'")
    expect(source).toContain('com.tencent.flue.WeChatAppEx')
    expect(source).toContain("$('AXManualAccessibility')")
    expect(source).toContain('NSNumber.numberWithBool')
    expect(source).toContain('isRealTitle(found.title)')
    expect(source).toContain('AXFocusedUIElement')
    expect(source).toContain('delay(0.2)')
    expect(source).toContain('visibleLines')
    expect(source).toContain('function findHeader')
    expect(source).toContain("ident === 'big_title_line_h_view'")
    expect(source).toContain('function selectedRowTitle')
    expect(source).toContain('AXSelectedRows')
    expect(source).toContain('AXMinimizedWindow')
    expect(source).not.toContain('title_view')
    expect(source).not.toContain('onTop')
    const main = source.slice(source.indexOf('function mainWindow'), source.indexOf('function cgOwnedWindow'))
    expect(main.indexOf('largestAxWindow(windows)')).toBeLessThan(main.indexOf("'AXFocusedWindow'"))
    expect(main).toContain('AXMainWindow')
    expect(source).toContain('function wechatApps()')
    expect(source).toContain('for (var a = 0; a < apps.length; a++)')
  })

  it('still trusts the Electron host and reconciles a failed Accessibility call', () => {
    expect(source).toContain('electronAccessibilityTrusted')
    expect(source).toContain('reconcileAxView(view, hostTrusted, workspaceRunning)')
    expect(source).toContain('hostTrusted')
  })

  it('still docks from System Events when the window-list snapshot has no bounds', () => {
    const finder = readFileSync('electron/findWeChat.ts', 'utf8')
    expect(finder).toContain('if (picked.bounds) return picked')
    expect(finder).toContain('listedWindowOutcome')
    expect(finder).toContain("picked.reason === 'hidden'")
    expect(finder).toContain('DARWIN_APPLESCRIPT')
    const script = readFileSync('electron/hostScripts.ts', 'utf8')
    expect(script).toContain('AXMinimized')
    expect(script).toContain('AXMinimizedWindow')
    expect(script).toContain('return "hidden"')
    expect(script).toContain('DARWIN_VISIBLE_SCRIPT')
    expect(script).toContain('DARWIN_ONSCREEN_SCRIPT')
    expect(script).toContain('every static text of w')
    const ocr = readFileSync('electron/wechat/titleOcr.ts', 'utf8')
    expect(ocr).toContain('CGPreflightScreenCaptureAccess')
    expect(ocr).not.toContain('CGRequestScreenCaptureAccess')
    expect(readFileSync('electron/findWeChat.ts', 'utf8')).toContain('noteWeChatSight')
  })
})
